/** 대본 프롬프트에 넣는 후킹 공식 블록 */
export function hookFormulaPromptBlock(opts?: { style?: 'polite' | 'ssul' }): string {
  const types = HOOK_TYPES.map(
    (t, i) =>
      `${i + 1}. ${t.name} (${t.id}) — ${t.principle}\n   잘 맞는 상품: ${t.fitsWhen}\n   공식: ${t.formulas.map((f) => `"${f}"`).join(' / ')}`,
  ).join('\n');
  const styleNote =
    opts?.style === 'ssul'
      ? '- 썰 말투(반말·3인칭 서사)로 쓸 때는 공식의 뜻만 살려 말투에 맞게 바꾼다. 예: "이거 모르고 사면 돈 버리는 거임."'
      : '- 정해진 말투(존댓말/반말)에 맞게 어미를 바꾼다.';
  return `[첫 문장 후킹 공식 — 아래 10가지 유형 중 이 상품·대상·말투에 가장 잘 맞는 하나를 골라 첫 문장을 쓴다]
${types}
규칙:
- 상품의 실제 특징·사용 상황·대상에 맞는 유형을 고른다. 매번 같은 유형만 쓰지 않는다.
- [ ] 는 상품 정보에 있는 사실로만 채운다. 숫자·기간·직업·후기·판매량은 상품 정보에 없으면 쓰지 않는다 (없는 수치를 만들지 말 것).
- 공식을 그대로 베끼지 말고 상품에 맞게 자연스럽게 바꾼다. 첫 문장은 짧게(공백 제외 25자 안팎).
${styleNote}
- 첫 문장 바로 다음 문장에서 그 후킹이 약속한 내용(문제·궁금증)을 이어 받아 이탈을 막는다.`;
}

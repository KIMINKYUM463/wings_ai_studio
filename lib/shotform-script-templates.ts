/** 쇼핑 숏폼 대본 템플릿 (벤치마킹 · 「○○형」 네이밍) */

export type ShotformTemplatePlatform = "instagram" | "youtube"

export type ShotformScriptTemplate = {
  id: string
  name: string
  platform: ShotformTemplatePlatform
  /** 한 줄 설명 (리스트용) — 키워드·구분 */
  blurb: string
  /** AI 생성 시 최우선 계약 */
  instruction: string
  /** 구조·말투 참고 (문장 복사 금지) */
  referenceExamples: string[]
  overview: {
    purpose: string
    guidelineSummary: string
    toneExamples: string[]
  }
  originalScript: {
    videoTitle: string
    evidenceLength: string
    body: string
  }
  guidelines: {
    hook: string
    development: string
    cta: string
    subtitle: string
    emphasis: string
  }
  examples: {
    good: string[]
    avoid: string[]
  }
}

function buildInstruction(name: string, g: ShotformScriptTemplate["guidelines"]): string {
  return `${name} 템플릿.
훅: ${g.hook}
전개: ${g.development}
CTA: ${g.cta}
자막: ${g.subtitle}
강조: ${g.emphasis}
제품명 직접 반복 금지. 구어체. 참고 예시 문장 복제 금지. 허위 수치·인증·할인율 창작 금지.`
}

const T = (
  partial: Omit<ShotformScriptTemplate, "instruction" | "referenceExamples"> & {
    referenceExamples?: string[]
  }
): ShotformScriptTemplate => {
  const instruction = buildInstruction(partial.name, partial.guidelines)
  return {
    ...partial,
    instruction,
    referenceExamples:
      partial.referenceExamples ||
      partial.examples.good.slice(0, 3).map((g) => g.replace(/^헤드카피:\s*/, "")),
  }
}


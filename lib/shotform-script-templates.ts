/** 목표 초 → 장면 수 (대략 4~8) */
export function sceneCountForSeconds(seconds: number): number {
  const s = Math.max(10, Math.min(60, Math.round(seconds || 30)))
  return Math.max(4, Math.min(8, Math.round(s / 6)))
}

/** TTS 1.2배속 기준 대략 글자 수 (공백 제외 목표) */
export function targetCharCountForSeconds(seconds: number): number {
  const s = Math.max(10, Math.min(60, Math.round(seconds || 30)))
  return Math.round(s * 9.17)
}

